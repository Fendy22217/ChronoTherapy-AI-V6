  function syntheticLabel(row) {
    // Labels are generated by transparent demonstration rules, not by clinical outcome data.
    const [age, sex, sbp, dbp, nightSbp, drugClass, frequency, sleep, wake, pattern, dizziness] = row;
    let score = 0;
    if (pattern === 1) score -= 1.7;          // nocturnal dipping pattern
    if (pattern === 2) score += 2.2;          // non-dipping pattern
    if (pattern === 3) score += 3.0;          // rising nighttime pattern
    if (nightSbp > 0) {
      const nocturnalDrop = sbp - nightSbp;
      if (nocturnalDrop <= 4) score += 1.8;
      else if (nocturnalDrop <= 9) score += 0.65;
      else if (nocturnalDrop >= 15) score -= 1.1;
    }
    if (drugClass === 4) score -= 0.35;        // diuretic class has a morning-oriented demonstration prior
    if (sleep === 2) score += 0.12;
    if (wake === 2) score += 0.08;
    // A small amount of label noise prevents a perfectly deterministic training set.
    let label = score >= 1.15 ? 1 : 0;          // 0 = morning, 1 = evening
    if (random() < 0.035) label = 1 - label;
    return label;
  }

