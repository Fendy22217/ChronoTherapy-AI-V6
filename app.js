  function drawChart() {
    const canvas = $("bpChart");
    const rect = canvas.getBoundingClientRect();
    const dpr = window.devicePixelRatio || 1;
    canvas.width = Math.max(320, rect.width * dpr);
    canvas.height = 205 * dpr;
    const ctx = canvas.getContext("2d");
    ctx.scale(dpr, dpr);
    const w = canvas.width / dpr, h = 205;
    const pad = { l: 38, r: 14, t: 15, b: 31 };
    const plotW = w-pad.l-pad.r, plotH = h-pad.t-pad.b;
    ctx.clearRect(0,0,w,h);
    ctx.font = "10px DM Sans, sans-serif";
    ctx.fillStyle = "#8c9aa2";
    [60,90,120,150,180,210].forEach(v => {
      const y = pad.t + (210-v)/150*plotH;
      ctx.strokeStyle = "#edf1f2"; ctx.beginPath(); ctx.moveTo(pad.l,y); ctx.lineTo(w-pad.r,y); ctx.stroke();
      ctx.fillText(String(v),4,y+3);
    });
    const stats = getAbpmStats();
    const readings = stats.all;
    if (!readings.length) {
      ctx.fillStyle = "#8c9aa2"; ctx.textAlign = "center";
      ctx.fillText("Belum ada pembacaan ABPM untuk divisualisasikan", w/2, h/2);
      ctx.textAlign = "left";
    } else {
      const hour = value => { const parts = value.split(":").map(Number); return parts[0] + parts[1]/60; };
      const xPos = value => pad.l + (hour(value)/24)*plotW;
      const yPos = value => pad.t + (210-value)/150*plotH;
      readings.forEach(item => {
        const x=xPos(item.time), y=yPos(item.sbp);
        ctx.beginPath(); ctx.arc(x,y,4.2,0,Math.PI*2);
        ctx.fillStyle=item.period === "awake" ? "#339f89" : "#8d7ac0"; ctx.fill();
        ctx.lineWidth=1.5; ctx.strokeStyle="#fff"; ctx.stroke();
      });
      if (stats.daySbp !== null && stats.nightSbp !== null) {
        ctx.setLineDash([5,4]);
        [[stats.daySbp,"#339f89"],[stats.nightSbp,"#8d7ac0"]].forEach(([v,c])=>{
          const y=yPos(v);ctx.beginPath();ctx.moveTo(pad.l,y);ctx.lineTo(w-pad.r,y);ctx.strokeStyle=c;ctx.lineWidth=1.3;ctx.stroke();
        });
        ctx.setLineDash([]);
      }
    }
    ["00","04","08","12","16","20","24"].forEach((v,i)=>ctx.fillText(v,pad.l+i/6*plotW-6,h-8));
  }

