  function buildResult() {
    const age = Number($("age").value);
    const sbp = Number($("sbp").value);
    const dbp = Number($("dbp").value);
    const abpmStats = refreshAbpmSummary();
    const nightSbp = abpmStats.sufficient ? abpmStats.nightSbp : Number($("nightSbp").value || 0);
    const drug = $("drugName").value.trim() || $("drugClass").value;
    const dizziness = $("dizziness").checked;
    const features = encodePatient();
    const votes = chronoModel.forest.map(tree => predictTree(tree, features));
    const nightVotes = votes.reduce((sum, value) => sum + value, 0);
    const direction = nightVotes > votes.length / 2 ? "Malam" : "Pagi";
    const winningVotes = direction === "Malam" ? nightVotes : votes.length - nightVotes;
    const patternValue = $("nightPattern").value;
    let reason = `Model prototipe memetakan kombinasi karakteristik, tekanan darah, golongan terapi, dan ritme harian ke kecenderungan waktu ${direction.toLowerCase()}.`;
    if (abpmStats.sufficient) reason += ` Rerata sistolik terjaga ${formatMetric(abpmStats.daySbp)} mmHg dan saat tidur ${formatMetric(abpmStats.nightSbp)} mmHg; penurunan sistolik malam terhitung ${formatMetric(abpmStats.sbpDip,"%")}.`;
    else if (nightSbp > 0) reason += ` Nilai sistolik malam yang dimasukkan adalah ${nightSbp} mmHg; pembacaan ABPM terperinci belum cukup untuk menghitung rerata periode.`;
    else reason += " Data pembacaan ABPM belum memadai untuk menghitung rerata siang dan malam.";
    if (patternValue !== "Tidak diketahui") reason += ` Pola malam yang dicatat: ${patternValue.toLowerCase()}.`;
    let caution = "Model ini masih bersifat eksperimental dan belum tervalidasi secara klinis. Hasil tidak boleh digunakan sendiri untuk menentukan atau mengubah waktu maupun dosis terapi.";
    if (dizziness || age >= 65) caution += " Faktor usia atau riwayat pusing/risiko jatuh perlu ditelaah khusus oleh tenaga kesehatan.";
    $("resultDirection").textContent = direction;
    $("resultSummary").textContent = reason;
    $("resultCaution").textContent = caution;
    $("outSbp").textContent = sbp;
    $("outDbp").textContent = dbp;
    $("outDrug").textContent = drug;
    const modelStatus = document.querySelector(".model-status");
    if (modelStatus) modelStatus.textContent = "Belum tervalidasi klinis";
    renderResultPanels(abpmStats);
    buildPrintableReport(abpmStats, direction, reason, {winning: winningVotes});
    $("resultCard").hidden = false;
    showPage("result");
    requestAnimationFrame(drawChart);
  }

