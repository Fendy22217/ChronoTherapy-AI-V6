  function validateStep() {
    const active = steps.find(el => Number(el.dataset.step) === currentStep);
    const required = [...active.querySelectorAll("[required]")];
    for (const field of required) {
      if (!field.value || (field.type === "number" && Number(field.value) <= 0)) {
        field.focus(); error.textContent = "Mohon lengkapi data yang wajib diisi."; return false;
      }
    }
    if (currentStep === 1 && Number($("age").value) < 18) {
      $("age").focus(); error.textContent = "Usia minimal untuk alur prototipe ini adalah 18 tahun."; return false;
    }
    if (currentStep === 2 && Number($("dbp").value) >= Number($("sbp").value)) {
      $("dbp").focus(); error.textContent = "Periksa kembali tekanan darah sistolik dan diastolik."; return false;
    }
    if (currentStep === 2) {
      const partial = [...document.querySelectorAll(".abpm-row")].find(row => {
        const time = row.querySelector(".abpm-time").value;
        const sbp = row.querySelector(".abpm-sbp").value;
        const dbp = row.querySelector(".abpm-dbp").value;
        return (time || sbp || dbp) && !(time && sbp && dbp);
      });
      if (partial) { error.textContent = "Lengkapi waktu, SBP, dan DBP pada setiap baris ABPM yang digunakan, atau hapus baris yang kosong."; return false; }
      const invalidPressure = [...document.querySelectorAll(".abpm-row")].find(row => {
        const sbp = Number(row.querySelector(".abpm-sbp").value || 0);
        const dbp = Number(row.querySelector(".abpm-dbp").value || 0);
        return sbp > 0 && dbp > 0 && dbp >= sbp;
      });
      if (invalidPressure) { error.textContent = "Periksa kembali pembacaan ABPM: nilai sistolik harus lebih tinggi daripada diastolik."; return false; }
    }
    return true;
  }

