  function gini(rows) {
    if (!rows.length) return 0;
    let positive = 0;
    for (const row of rows) positive += row.y;
    const p = positive / rows.length;
    return 2 * p * (1 - p);
  }

  function majority(rows) {
    let positive = 0;
    for (const row of rows) positive += row.y;
    return positive >= rows.length / 2 ? 1 : 0;
  }

  function buildTree(rows, rng, importance, depth = 0, maxDepth = 5, minLeaf = 14) {
    const prediction = majority(rows);
    if (depth >= maxDepth || rows.length < minLeaf * 2 || gini(rows) < 0.015) {
      return { leaf: true, prediction };
    }

    const featureCount = rows[0].x.length;
    const featureIds = Array.from({ length: featureCount }, (_, i) => i);
    for (let i = featureIds.length - 1; i > 0; i--) {
      const j = Math.floor(rng() * (i + 1));
      [featureIds[i], featureIds[j]] = [featureIds[j], featureIds[i]];
    }
    const selectedFeatures = featureIds.slice(0, 3);
    const parentImpurity = gini(rows);
    let best = null;

    for (const feature of selectedFeatures) {
      let min = Infinity, max = -Infinity;
      for (const row of rows) {
        const value = row.x[feature];
        if (value < min) min = value;
        if (value > max) max = value;
      }
      if (min === max) continue;

      for (let trial = 0; trial < 5; trial++) {
        const a = rows[Math.floor(rng() * rows.length)].x[feature];
        const b = rows[Math.floor(rng() * rows.length)].x[feature];
        const threshold = a === b ? randBetween(min, max) : (a + b) / 2;
        const left = [], right = [];
        for (const row of rows) {
          (row.x[feature] <= threshold ? left : right).push(row);
        }
        if (left.length < minLeaf || right.length < minLeaf) continue;
        const weighted = (left.length / rows.length) * gini(left) +
                         (right.length / rows.length) * gini(right);
        const gain = parentImpurity - weighted;
        if (!best || gain > best.gain) best = { feature, threshold, left, right, gain };
      }
    }

    if (!best || best.gain < 0.002) return { leaf: true, prediction };
    importance[best.feature] += best.gain * rows.length;
    return {
      leaf: false,
      feature: best.feature,
      threshold: best.threshold,
      left: buildTree(best.left, rng, importance, depth + 1, maxDepth, minLeaf),
      right: buildTree(best.right, rng, importance, depth + 1, maxDepth, minLeaf),
      prediction
    };
  }

  function predictTree(tree, features) {
    let node = tree;
    while (!node.leaf) node = features[node.feature] <= node.threshold ? node.left : node.right;
    return node.prediction;
  }

  function trainRandomForest() {
    const trainingRows = createSyntheticDataset(5000);
    const treeCount = 19;
    const forest = [];
    const importance = Array(11).fill(0);
    const forestRandom = makeRandom(7312026);
    for (let t = 0; t < treeCount; t++) {
      const bootstrap = [];
      for (let i = 0; i < 760; i++) {
        bootstrap.push(trainingRows[Math.floor(forestRandom() * trainingRows.length)]);
      }
      forest.push(buildTree(bootstrap, forestRandom, importance));
    }
    const totalImportance = importance.reduce((sum, value) => sum + value, 0) || 1;
    const normalizedImportance = importance.map(value => value / totalImportance * 100);
    return { forest, trainingCount: trainingRows.length, treeCount, importance: normalizedImportance };
  }

